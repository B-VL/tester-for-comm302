// Helper to generate realistic historical price curve
function generateHistory(
  basePrice: number,
  trendPercent: number,
  volatility = 0.015,
  pointsCount = 40
): Record<'1D' | '5D' | '1M' | '6M' | '1Y' | 'ALL', any[]> {
  const timeframes: ('1D' | '5D' | '1M' | '6M' | '1Y' | 'ALL')[] = ['1D', '5D', '1M', '6M', '1Y', 'ALL'];
  const res: any = {};

  timeframes.forEach((tf) => {
    const pts = [];
    const count = tf === '1D' ? 32 : tf === '5D' ? 35 : tf === '1M' ? 30 : 45;
    let curr = basePrice * (1 - (trendPercent / 100) * (tf === '1D' ? 1 : tf === '5D' ? 2 : 3.5));
    const stepTarget = basePrice;
    const step = (stepTarget - curr) / count;

    for (let i = 0; i < count; i++) {
      const progress = i / count;
      const noise = (Math.sin(i * 0.8) + (Math.random() - 0.48) * 2) * (basePrice * volatility);
      curr = curr + step + noise * 0.2;
      const open = curr;
      const high = curr + Math.abs(noise) * 0.7;
      const low = curr - Math.abs(noise) * 0.7;
      const close = curr + (Math.random() - 0.5) * (basePrice * volatility * 0.5);
      const vol = Math.floor(Math.random() * 500000 + 100000);

      let timeLabel = '';
      if (tf === '1D') {
        const hour = 9 + Math.floor((i / count) * 7);
        const min = Math.floor(((i / count) * 420) % 60);
        timeLabel = `${hour.toString().padStart(2, '0')}:${min.toString().padStart(2, '0')}`;
      } else if (tf === '5D') {
        timeLabel = `Day ${Math.floor(i / 7) + 1} ${10 + (i % 6)}:00`;
      } else {
        timeLabel = `Sep ${Math.min(28, i + 1)}`;
      }

      pts.push({
        time: timeLabel,
        price: Number(close.toFixed(2)),
        open: Number(open.toFixed(2)),
        high: Number(high.toFixed(2)),
        low: Number(low.toFixed(2)),
        close: Number(close.toFixed(2)),
        volume: vol,
      });
    }
    // ensure last price is basePrice
    pts[pts.length - 1].close = basePrice;
    pts[pts.length - 1].price = basePrice;
    res[tf] = pts;
  });

  return res;
}

